    /**
     * Formats a date in Slovak, e.g. "utorok 6. októbra 2026".
     * Uses intl when available, falls back to a plain numeric format.
     */
    function sk_date(Time|DateTimeInterface|string|null $date = null, string $pattern = "EEEE d. MMMM yyyy"): string
    {
        $time = $date === null ? Time::now() : ($date instanceof Time ? $date : Time::parse(is_string($date) ? $date : $date->format(DATE_ATOM)));

        if (class_exists(IntlDateFormatter::class)) {
            $formatter = new IntlDateFormatter('sk_SK', IntlDateFormatter::FULL, IntlDateFormatter::NONE, $time->getTimezone(), IntlDateFormatter::GREGORIAN, $pattern);

            return (string) $formatter->format($time->getTimestamp());
        }

        return $time->format('j. n. Y');
    }
